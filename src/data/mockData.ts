// Automatically creates or retrieves a permanent, unique City ID for the user
export function getOrCreateUniqueCityId(): string {
  try {
    const existing = localStorage.getItem('fincity_unique_city_id');
    if (existing && /^CTY-\d{4}$/.test(existing)) {
      return existing;
    }
    const randomCode = Math.floor(1000 + Math.random() * 9000);
    const newId = `CTY-${randomCode}`;
    localStorage.setItem('fincity_unique_city_id', newId);
    return newId;
  } catch {
    return 'CTY-2037';
  }
}

